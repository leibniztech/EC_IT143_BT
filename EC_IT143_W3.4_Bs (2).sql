--Question:
--Our sales director wants to evaluate the performance of our sales territories. We need to identify which territories generated the highest sales during 2013. Can you provide the total sales revenue for each territory, ranked from highest to lowest?

--answer:
-- This query calculates the total sales revenue generated by
-- each sales territory in 2013 using the TotalDue amount from
-- Sales.SalesOrderHeader. Results are ranked from highest to
-- lowest revenue.

--sql query :
SELECT
    st.Name AS TerritoryName,
    st.[Group] AS TerritoryGroup,
    SUM(soh.TotalDue) AS TotalSalesRevenue
FROM Sales.SalesOrderHeader soh
INNER JOIN Sales.SalesTerritory st
    ON soh.TerritoryID = st.TerritoryID
WHERE YEAR(soh.OrderDate) = 2013
GROUP BY
    st.Name,
    st.[Group]
ORDER BY TotalSalesRevenue DESC;

GO

