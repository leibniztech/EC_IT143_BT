--Question:
--Which five products had the highest total quantities ordered? Can you include their product names and total quantities sold?

--answer:-- This query joins Production.Product and
-- Sales.SalesOrderDetail to calculate the total quantity
-- sold for each product. The results are ranked from
-- highest to lowest, and only the top five products
-- are returned.

--sql query:
SELECT TOP 5
    p.ProductID,
    p.Name AS ProductName,
    SUM(sod.OrderQty) AS TotalQuantitySold
FROM Production.Product p
INNER JOIN Sales.SalesOrderDetail sod
    ON p.ProductID = sod.ProductID
GROUP BY
    p.ProductID,
    p.Name
ORDER BY TotalQuantitySold DESC;

GO


