-- Question :
-- Which products have a ListPrice greater than $1000??

--Answer:This query retrieves products from the Production.Product
-- table whose ListPrice exceeds $1000 and displays them
-- from highest to lowest price. result : product ranging from 3578.27 to 1003.91

--sql query : 
SELECT
    ProductID,
    Name,
    ListPrice
FROM Production.Product
WHERE ListPrice > 1000
ORDER BY ListPrice DESC;

GO

